#!/bin/sh
# Open a pull request to microsoft/winget-pkgs with the rendered winget
# manifests of one release, from the fork OWNER/winget-pkgs. The token
# (GH_TOKEN) needs `public_repo` scope, or a fine-grained token with
# contents + pull requests write on the fork.
#
#   GH_TOKEN=... scripts/winget-submit.sh OWNER VERSION MANIFEST_DIR
#
# Does nothing when winget-pkgs already has this version or a pull request
# for it is open.
set -eu

[ "$#" -eq 3 ] || { echo "usage: $0 OWNER VERSION MANIFEST_DIR" >&2; exit 2; }
owner=$1 version=$2 dir=$3
here=$(cd "$(dirname "$0")" && pwd)
id=dmdhrumilmistry.kubera
upstream=microsoft/winget-pkgs
fork="$owner/winget-pkgs"
branch="$id-$version"
pkgdir="manifests/d/dmdhrumilmistry/kubera"

exists() { gh api "$1" --silent >/dev/null 2>&1; }

if exists "repos/$upstream/contents/$pkgdir/$version"; then
    echo "winget-pkgs already has $id $version"
    exit 0
fi
open=$(gh api "repos/$upstream/pulls?state=open&head=$owner:$branch" --jq 'length')
if [ "$open" != "0" ]; then
    echo "a pull request for $id $version is already open"
    exit 0
fi
if exists "repos/$upstream/contents/$pkgdir"; then
    title="New version: $id version $version"
else
    title="New package: $id version $version"
fi

# Bring the fork's default branch up to date, then branch from it.
gh api -X POST "repos/$fork/merge-upstream" -f branch=master --silent
if ! exists "repos/$fork/git/ref/heads/$branch"; then
    base=$(gh api "repos/$fork/git/ref/heads/master" --jq .object.sha)
    gh api -X POST "repos/$fork/git/refs" -f ref="refs/heads/$branch" -f sha="$base" --silent
fi
for f in "$dir"/*.yaml; do
    "$here/gh-put-file.sh" "$fork" "$pkgdir/$version/$(basename "$f")" "$f" "$title" "$branch"
done

gh api -X POST "repos/$upstream/pulls" \
    -f title="$title" \
    -f head="$owner:$branch" \
    -f base=master \
    -f body="Manifests generated by the kubera release workflow from the published release assets and their SHA-256 checksums: https://github.com/dmdhrumilmistry/kubera/releases/tag/v$version" \
    --jq .html_url
